/*
operadores relacionais em JS
== -> igual
=== -> estritamente igual valor e tipo
!= ->diferente
> -> maior que
< ->menor que
<= ->menor ou igual a
>= -> maior ou igual a

*/
//exemplos

let num1 = 7
let num2 = "7"
let num3 = 3

console.log(num1 == num2) //verifica apenas valor
console.log(num1 === num2)//verifica valor e tipo
console.log(num1 != num2)//verifica apenas valor
console.log(num1 !== num2)//verifica valor e tipo
console.log(num1 > num3)//verifica se valor é maior
console.log(num1 < num3)//verifica se valor é menor 
console.log(num1 <= num3)//verifica se valor é menor ou igual
console.log(num1 >= num3)//verifica se valor é maior ou igual